/**
 * Failure modes: is the intake ever worse off with SweepLine than without it? Runs each simulated
 * row of src/config/failureModes.ts (a stress-test scenario, or a fault injected into steady
 * operation) on the same bloom seeds with and without SweepLine, and counts intake contacts over
 * the run. The tide-turn row comes from the multi-seed study; the air/power row is a design property.
 *
 *   npm run study:failures              # 3 seeds, 30 min; writes src/data/failures.generated.ts
 *   npm run study:failures -- seeds=5 minutes=45
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { FailureMode } from '../src/config/failureModes';
import type { FailureOutcome, FailuresData } from '../src/data/failuresTypes';
import { getScenario } from '../src/simulation/scenarios';
import { controller } from '../src/simulation/SimController';
import { DEFAULT_PARAMS, type FailureKey, type SimParams } from '../src/simulation/types';

const arg = (k: string, d: number) => Number(process.argv.find((a) => a.startsWith(`${k}=`))?.split('=')[1] ?? d);
const N = arg('seeds', 3);
const MINUTES = arg('minutes', 30);
const SEEDS = Array.from({ length: N }, (_, k) => 1000 + k * 7919);

controller.setPublisher(() => {}, () => {});

interface Run {
  /** A stress-test scenario, or steady operation with these parameters. */
  scenario?: string;
  params?: Partial<SimParams>;
  /** Fault injected this many simulated seconds into the run. */
  inject?: { at: number; key: FailureKey };
}

const RUNS: Partial<Record<FailureMode['key'], Run>> = {
  transfer: { scenario: 'transfer-failure' },
  transferBoth: { scenario: 'safeopen' },
  jets: { params: { activeFlow: false } },
  fouling: { inject: { at: 40, key: 'curtainOverload' } },
  waves: { scenario: 'high-waves' },
  current: { scenario: 'high-current' },
  deep: { scenario: 'deep' },
  slack: { scenario: 'slack-tide' },
  late: { scenario: 'workboat' },
};

async function once(run: Run, seed: number) {
  if (run.scenario) {
    const sc = getScenario(run.scenario)!;
    controller.params = { ...DEFAULT_PARAMS, ...sc.params, seed };
    await controller.restart(sc.start, sc);
  } else {
    controller.params = { ...DEFAULT_PARAMS, ...run.params, seed };
    await controller.restart('steady', null);
  }
  controller.setSpeed(40);
  const b0 = controller.baseline.counters.intakeContacts;
  const s0 = controller.sweepline.counters.intakeContacts;
  // A steady start has already run its pre-roll: time the run from here.
  const start = controller.simTime;
  let injected = !run.inject;
  while (controller.simTime - start < MINUTES * 60) {
    if (!injected && controller.simTime - start >= run.inject!.at) {
      controller.injectFailure(run.inject!.key);
      injected = true;
    }
    controller.frame(0.1);
  }
  return {
    sweep: controller.sweepline.counters.intakeContacts - s0,
    base: controller.baseline.counters.intakeContacts - b0,
    status: controller.computeStatus().code as string,
  };
}

const t0 = performance.now();
const outcomes: FailuresData['outcomes'] = {};
for (const [key, run] of Object.entries(RUNS) as Array<[FailureMode['key'], Run]>) {
  const r: Array<Awaited<ReturnType<typeof once>>> = [];
  for (const seed of SEEDS) {
    r.push(await once(run, seed));
    controller.clearAllFailures();
  }
  const mean = (f: (x: (typeof r)[number]) => number): number => Math.round((r.reduce((s, x) => s + f(x), 0) / r.length) * 10) / 10;
  const statuses = r.map((x) => x.status);
  const status = statuses.sort((a, b) => statuses.filter((s) => s === b).length - statuses.filter((s) => s === a).length)[0];
  const o: FailureOutcome = { sweep: mean((x) => x.sweep), base: mean((x) => x.base), worstExcess: Math.max(0, ...r.map((x) => x.sweep - x.base)), status };
  outcomes[key] = o;
  console.log(`  ${key.padEnd(13)} ${String(o.sweep).padStart(7)} vs ${String(o.base).padStart(7)} without · worst excess ${o.worstExcess} · ${status}`);
}

const data: FailuresData = { generatedAt: new Date().toISOString().slice(0, 10), minutes: MINUTES, seeds: SEEDS, outcomes };
const out = resolve(process.cwd(), 'src/data/failures.generated.ts');
writeFileSync(
  out,
  `// Generated by scripts/failure-study.ts on ${data.generatedAt} — do not edit by hand.\n` +
    `// Intake contacts over each failure run with and without SweepLine (same bloom seeds).\n` +
    `import type { FailuresData } from './failuresTypes';\n\n` +
    `export const FAILURES_DATA: FailuresData = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`wrote ${out} · ${((performance.now() - t0) / 60000).toFixed(1)} min`);
const worse = Object.entries(outcomes).filter(([, o]) => o!.worstExcess > 0);
if (worse.length) console.log(`WORSE THAN BASELINE: ${worse.map(([k]) => k).join(', ')}`);
