/**
 * How much do the headline results depend on the particular bloom? Runs the reference sequence
 * (60 simulated minutes from the bloom approach) for many bloom seeds, and the recorded tide turn
 * (Twin-Line and single line, 3 h after the turn) for a few, and reports means with 95 % confidence
 * intervals. Each run compares SweepLine with its own same-seed baseline.
 *
 *   npm run study:seeds                 # 20 reference seeds, 5 tide seeds; writes src/data/seeds.generated.ts
 *   npm run study:seeds -- seeds=10 tideSeeds=3
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { SeedStat, SeedsData } from '../src/data/seedsTypes';
import { computeEngineMetrics } from '../src/simulation/metrics';
import { getScenario } from '../src/simulation/scenarios';
import { controller } from '../src/simulation/SimController';
import { TIDE } from '../src/simulation/tide';
import { DEFAULT_PARAMS } from '../src/simulation/types';

const arg = (k: string, d: number) => Number(process.argv.find((a) => a.startsWith(`${k}=`))?.split('=')[1] ?? d);
const N = arg('seeds', 20);
const NT = arg('tideSeeds', 5);
const MINUTES = 60;

controller.setPublisher(() => {}, () => {});

/** Two-sided 95 % Student-t quantiles by degrees of freedom. */
const T95: Record<number, number> = { 1: 12.71, 2: 4.3, 3: 3.18, 4: 2.78, 5: 2.57, 6: 2.45, 7: 2.36, 8: 2.31, 9: 2.26, 10: 2.23, 14: 2.14, 19: 2.09, 29: 2.05 };
const tq = (df: number) => T95[df] ?? T95[Object.keys(T95).map(Number).filter((k) => k <= df).pop() ?? 1];
function stat(v: number[]): SeedStat {
  const n = v.length;
  const mean = v.reduce((s, x) => s + x, 0) / n;
  const sd = Math.sqrt(v.reduce((s, x) => s + (x - mean) ** 2, 0) / Math.max(1, n - 1));
  const h = (tq(n - 1) * sd) / Math.sqrt(n);
  const r = (x: number) => Math.round(x * 10000) / 10000;
  return { mean: r(mean), lo: r(mean - h), hi: r(mean + h), min: r(Math.min(...v)), max: r(Math.max(...v)), n };
}

async function reference(seed: number) {
  controller.params = { ...DEFAULT_PARAMS, seed };
  await controller.restart('sequence', null);
  controller.setSpeed(40);
  while (controller.simTime < MINUTES * 60) controller.frame(0.1);
  const b = computeEngineMetrics(controller.baseline);
  const s = computeEngineMetrics(controller.sweepline);
  return {
    reduction: 1 - (s.intakeContactPct ?? 0) / Math.max(1e-9, b.intakeContactPct ?? 1),
    diversion: s.diversionEfficiency ?? 0,
    underSkirt: s.underSkirtPct ?? 0,
  };
}

async function tideTurn(seed: number, twinLine: boolean) {
  const sc = getScenario('tide-turn')!;
  controller.params = { ...DEFAULT_PARAMS, ...sc.params, seed, twinLine };
  await controller.restart(sc.start, sc);
  controller.setSpeed(40);
  const hours = () => controller.params.tideStart + controller.simTime / 3600;
  while (hours() < TIDE.referenceTurn) controller.frame(0.1);
  const b0 = controller.baseline.counters.intakeContacts;
  const s0 = controller.sweepline.counters.intakeContacts;
  while (hours() < TIDE.referenceTurn + 3) controller.frame(0.1);
  const b = controller.baseline.counters.intakeContacts - b0;
  const s = controller.sweepline.counters.intakeContacts - s0;
  return 1 - s / Math.max(1, b);
}

const t0 = performance.now();
const ref = { reduction: [] as number[], diversion: [] as number[], underSkirt: [] as number[] };
for (let k = 0; k < N; k++) {
  const r = await reference(1000 + k * 7919);
  ref.reduction.push(r.reduction);
  ref.diversion.push(r.diversion);
  ref.underSkirt.push(r.underSkirt);
  process.stdout.write(`\r  reference ${k + 1}/${N}`);
}
console.log();
const twin: number[] = [];
const single: number[] = [];
for (let k = 0; k < NT; k++) {
  twin.push(await tideTurn(2000 + k * 104729, true));
  single.push(await tideTurn(2000 + k * 104729, false));
  process.stdout.write(`\r  tide turn ${k + 1}/${NT}`);
}
console.log();

const data: SeedsData = {
  generatedAt: new Date().toISOString().slice(0, 10),
  reference: { minutes: MINUTES, reduction: stat(ref.reduction), diversion: stat(ref.diversion), underSkirt: stat(ref.underSkirt) },
  tideTurn: { hoursAfter: 3, twin: stat(twin), single: stat(single) },
};
const pct = (s: SeedStat) => `${(s.mean * 100).toFixed(1)}% (95% CI ${(s.lo * 100).toFixed(1)}–${(s.hi * 100).toFixed(1)}, range ${(s.min * 100).toFixed(1)}–${(s.max * 100).toFixed(1)}, n=${s.n})`;
console.log(`reference, ${MINUTES} min: fewer intake contacts ${pct(data.reference.reduction)}`);
console.log(`  diversion ${pct(data.reference.diversion)} · under-skirt ${pct(data.reference.underSkirt)}`);
console.log(`tide turn, 3 h after: Twin-Line ${pct(data.tideTurn.twin)} · single line ${pct(data.tideTurn.single)}`);
const out = resolve(process.cwd(), 'src/data/seeds.generated.ts');
writeFileSync(
  out,
  `// Generated by scripts/seed-study.ts on ${data.generatedAt} — do not edit by hand.\n` +
    `// Headline results across bloom seeds (means with 95 % confidence intervals), each against its own same-seed baseline.\n` +
    `import type { SeedsData } from './seedsTypes';\n\n` +
    `export const SEEDS_DATA: SeedsData = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`wrote ${out} · ${((performance.now() - t0) / 60000).toFixed(1)} min`);
