/**
 * Which assumptions does the headline result depend on? Runs the reference sequence (60 simulated
 * minutes from the bloom approach) with each factor in src/config/sensitivity.ts set to the low and
 * the high end of its range, one at a time, on the same bloom seeds as the reference, and reports
 * the share of intake contacts avoided against each run's own same-seed baseline.
 *
 *   npm run study:sensitivity             # 3 seeds per point; writes src/data/sensitivity.generated.ts
 *   npm run study:sensitivity -- seeds=5
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ASSUMPTIONS } from '../src/config/assumptions';
import { SENSITIVITY_FACTORS, type SensitivityFactor } from '../src/config/sensitivity';
import type { SensitivityData } from '../src/data/sensitivityTypes';
import { computeEngineMetrics } from '../src/simulation/metrics';
import { controller } from '../src/simulation/SimController';
import { DEFAULT_PARAMS, type SimParams } from '../src/simulation/types';

const arg = (k: string, d: number) => Number(process.argv.find((a) => a.startsWith(`${k}=`))?.split('=')[1] ?? d);
const N = arg('seeds', 3);
const MINUTES = 60;
const SEEDS = Array.from({ length: N }, (_, k) => 1000 + k * 7919);

controller.setPublisher(() => {}, () => {});

// The study varies model assumptions in place and restores them after each point.
const agent = ASSUMPTIONS.agent as { swimSpeedMin: number; swimSpeedMax: number };
const curtain = ASSUMPTIONS.curtain as { redirectGain: number; liftCoefficient: number };
const original = { ...agent, ...curtain };

/** Sets one factor to `v`; returns the run parameters (model assumptions are set in place). */
function apply(key: SensitivityFactor['key'], v: number): Partial<SimParams> {
  switch (key) {
    case 'current':
      return { currentSpeed: v };
    case 'depth':
      return { bloomMeanDepth: v };
    case 'density':
      return { bloomDensity: v };
    case 'waves':
      return { waveHeight: v };
    case 'swim':
      agent.swimSpeedMin = original.swimSpeedMin * v;
      agent.swimSpeedMax = original.swimSpeedMax * v;
      return {};
    case 'slide':
      curtain.redirectGain = v;
      return {};
    case 'blowback':
      curtain.liftCoefficient = original.liftCoefficient * v;
      return {};
    case 'jets':
      return v === 0 ? { activeFlow: false } : { jetLevel: v };
  }
}

function restore() {
  agent.swimSpeedMin = original.swimSpeedMin;
  agent.swimSpeedMax = original.swimSpeedMax;
  curtain.redirectGain = original.redirectGain;
  curtain.liftCoefficient = original.liftCoefficient;
}

async function run(seed: number, over: Partial<SimParams>) {
  controller.params = { ...DEFAULT_PARAMS, ...over, seed };
  await controller.restart('sequence', null);
  controller.setSpeed(40);
  while (controller.simTime < MINUTES * 60) controller.frame(0.1);
  const b = computeEngineMetrics(controller.baseline);
  const s = computeEngineMetrics(controller.sweepline);
  return 1 - (s.intakeContactPct ?? 0) / Math.max(1e-9, b.intakeContactPct ?? 1);
}

async function point(label: string, set: () => Partial<SimParams>) {
  const v: number[] = [];
  for (const seed of SEEDS) {
    v.push(await run(seed, set()));
    restore();
  }
  const mean = v.reduce((s, x) => s + x, 0) / v.length;
  console.log(`  ${label.padEnd(36)} ${(mean * 100).toFixed(1)}%  [${v.map((x) => (x * 100).toFixed(1)).join(', ')}]`);
  return Math.round(mean * 10000) / 10000;
}

const t0 = performance.now();
const base = await point('reference', () => ({}));
const factors = {} as SensitivityData['factors'];
for (const f of SENSITIVITY_FACTORS) {
  factors[f.key] = {
    low: await point(`${f.label} ${f.low} ${f.unit}`, () => apply(f.key, f.low)),
    high: await point(`${f.label} ${f.high} ${f.unit}`, () => apply(f.key, f.high)),
  };
}

const data: SensitivityData = { generatedAt: new Date().toISOString().slice(0, 10), minutes: MINUTES, seeds: SEEDS, base, factors };
const out = resolve(process.cwd(), 'src/data/sensitivity.generated.ts');
writeFileSync(
  out,
  `// Generated by scripts/sensitivity-study.ts on ${data.generatedAt} — do not edit by hand.\n` +
    `// Share of intake contacts avoided with each factor at the ends of its range, against same-seed baselines.\n` +
    `import type { SensitivityData } from './sensitivityTypes';\n\n` +
    `export const SENSITIVITY_DATA: SensitivityData = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`wrote ${out} · ${((performance.now() - t0) / 60000).toFixed(1)} min`);
