/**
 * Turns the raw study runs (scripts/study-all.sh) into src/data/study.generated.ts, so every number
 * the app shows traces to a named run.
 *
 *   node scripts/study-collect.mjs <runs-dir>
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2] ?? '.study';
const load = (n) => {
  const p = resolve(dir, `${n}.json`);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
};
const SEEDS = [1000, 8919, 16838, 24757, 32676];
const seeds = SEEDS.map((s) => load(`reference-${s}`)).filter(Boolean);
if (!seeds.length) throw new Error(`no runs in ${dir}`);
const min = (a) => Math.min(...a);
const max = (a) => Math.max(...a);
const round = (v, d = 3) => (v === null || v === undefined ? null : Math.round(v * 10 ** d) / 10 ** d);
const brief = (r) =>
  r && {
    hours: r.hours,
    with: round(r.sScreens),
    without: round(r.bScreens, 1),
    collected: round(r.collected, 1),
    peakOnNet: round(r.peakOnNetT, 1),
    maxHead: round(r.maxHead, 4),
    reliefAt: r.reliefAt,
    closes: r.closes,
  };

const cases = {};
for (const n of ['single', 'moon', 'deep', 'fouled', 'storm', 'tide', 'tearBusy', 'tearBusySingle', 'leak10', 'leak10Single', 'pumps', 'overload', 'debris']) {
  const r = load(n);
  if (r) cases[n] = brief(r);
}
const sensitivity = {};
for (const k of ['slide', 'leak', 'snag', 'swim', 'flow']) sensitivity[k] = { low: brief(load(`sens-${k}-low`)), high: brief(load(`sens-${k}-high`)) };

const ref = seeds[0];
const data = {
  generatedAt: new Date().toISOString().slice(0, 10),
  hours: ref.hours,
  bloomTph: 25,
  blooms: {
    n: seeds.length,
    baseLow: round(min(seeds.map((r) => r.bScreens)), 1),
    baseHigh: round(max(seeds.map((r) => r.bScreens)), 1),
    withHigh: round(max(seeds.map((r) => r.sScreens))),
    collectedLow: round(min(seeds.map((r) => r.collected)), 1),
    collectedHigh: round(max(seeds.map((r) => r.collected)), 1),
    balanced: seeds.every((r) => r.closes),
  },
  reference: { ...brief(ref), deratedAt: ref.bDerate, trippedAt: ref.bTrip, series: ref.series.map((p) => ({ t: Math.round(p.t), b: round(p.b, 2), s: round(p.s, 3) })) },
  cases,
  sensitivity,
};
writeFileSync(
  resolve(here, '../src/data/study.generated.ts'),
  `// Generated by scripts/study-collect.mjs on ${data.generatedAt} — do not edit by hand.\n// Model results: same bloom with and without SweepLine.\nexport const STUDY = ${JSON.stringify(data, null, 1)} as const;\n`,
);
console.log('study.generated.ts:', seeds.length, 'blooms,', Object.keys(cases).length, 'cases');
