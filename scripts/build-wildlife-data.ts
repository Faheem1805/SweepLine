/**
 * Build the wildlife-presence summary for the twin (run manually, not at app runtime):
 *
 *   npm run build:wildlife            # uses the cached download in .cache/wildlife
 *   npm run build:wildlife -- --refresh
 *
 * Source: OBIS occurrence records of green turtles (Chelonia mydas) in a box around the reference
 * site (in practice the satellite fixes of the Gulf Green Turtle Project 2016–2019), and GBIF
 * records of dugongs (Dugong dugon) in western Abu Dhabi waters. Output:
 * src/data/wildlife.generated.ts — counts by distance from the site, nothing fetched at runtime.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { MAP_INTRO_DATA } from '../src/data/mapIntro.generated';
import type { WildlifeData } from '../src/data/wildlifeTypes';

const REFRESH = process.argv.includes('--refresh');
const CACHE = resolve(process.cwd(), '.cache/wildlife');
const OUT = resolve(process.cwd(), 'src/data/wildlife.generated.ts');
const LAT0 = MAP_INTRO_DATA.projection.lat0;
const LON0 = MAP_INTRO_DATA.projection.lon0;
/** Search boxes (lon/lat): around the site for turtles, western Abu Dhabi waters for dugongs. */
const TURTLE_BOX = 'POLYGON((52.15 23.95,52.85 23.95,52.85 24.45,52.15 24.45,52.15 23.95))';
const DUGONG_BOX = 'POLYGON((51.5 23.6,54.0 23.6,54.0 24.8,51.5 24.8,51.5 23.6))';

async function cached(name: string, url: string): Promise<unknown> {
  mkdirSync(CACHE, { recursive: true });
  const file = resolve(CACHE, name);
  if (!REFRESH && existsSync(file)) return JSON.parse(readFileSync(file, 'utf8'));
  console.log(`  ↓ ${url}`);
  const res = await fetch(url, { headers: { 'User-Agent': 'SweepLine-wildlife-build/1.0 (one-off build-time data preparation)' } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const body = await res.text();
  writeFileSync(file, body);
  return JSON.parse(body);
}

const DEG = Math.PI / 180;
const km = (lat: number, lon: number) =>
  6371.0088 * 2 * Math.asin(Math.sqrt(Math.sin(((lat - LAT0) * DEG) / 2) ** 2 + Math.cos(LAT0 * DEG) * Math.cos(lat * DEG) * Math.sin(((lon - LON0) * DEG) / 2) ** 2));

interface Occurrence {
  decimalLatitude?: number;
  decimalLongitude?: number;
  datasetName?: string;
  eventDate?: string;
}

async function main(): Promise<void> {
  console.log('wildlife records');
  const obis = (await cached(
    'obis_chelonia_mydas.json',
    `https://api.obis.org/v3/occurrence?scientificname=Chelonia%20mydas&geometry=${encodeURIComponent(TURTLE_BOX)}&size=1000`,
  )) as { total: number; results: Occurrence[] };
  const gbif = (await cached(
    'gbif_dugong_dugon.json',
    `https://api.gbif.org/v1/occurrence/search?scientificName=Dugong%20dugon&geometry=${encodeURIComponent(DUGONG_BOX)}&limit=300`,
  )) as { count: number; results: Occurrence[] };

  const turtles = obis.results.filter((r) => r.decimalLatitude !== undefined && r.decimalLongitude !== undefined);
  const dist = turtles.map((r) => km(r.decimalLatitude!, r.decimalLongitude!)).sort((a, b) => a - b);
  const years = turtles.map((r) => (r.eventDate ?? '').slice(0, 4)).filter(Boolean).sort();
  const datasets = [...new Set(turtles.map((r) => r.datasetName ?? 'unnamed dataset'))];
  const dugongDist = gbif.results
    .filter((r) => r.decimalLatitude !== undefined && r.decimalLongitude !== undefined)
    .map((r) => km(r.decimalLatitude!, r.decimalLongitude!))
    .sort((a, b) => a - b);

  const data: WildlifeData = {
    generatedAt: new Date().toISOString().slice(0, 10),
    turtles: {
      species: 'Green turtle (Chelonia mydas)',
      source: `OBIS · ${datasets.join(', ')}`,
      years: years.length ? `${years[0]}–${years[years.length - 1]}` : '',
      records: turtles.length,
      within2km: dist.filter((d) => d <= 2).length,
      within10km: dist.filter((d) => d <= 10).length,
      nearestKm: dist.length ? Math.round(dist[0] * 10) / 10 : null,
    },
    dugongs: {
      species: 'Dugong (Dugong dugon)',
      source: 'GBIF occurrence records, western Abu Dhabi waters',
      records: dugongDist.length,
      nearestKm: dugongDist.length ? Math.round(dugongDist[0]) : null,
    },
  };
  console.log(
    `  green turtles: ${data.turtles.records} records (${data.turtles.years}), ${data.turtles.within10km} within 10 km, nearest ${data.turtles.nearestKm} km · dugongs: ${data.dugongs.records} records, nearest ${data.dugongs.nearestKm} km`,
  );
  writeFileSync(
    OUT,
    `// Generated by scripts/build-wildlife-data.ts on ${data.generatedAt} — do not edit by hand.\n` +
      `// Sources: ${data.turtles.source}; ${data.dugongs.source}.\n` +
      `import type { WildlifeData } from './wildlifeTypes';\n\n` +
      `export const WILDLIFE_DATA: WildlifeData = ${JSON.stringify(data, null, 2)};\n`,
  );
  console.log(`  wrote ${OUT}`);
}

await main();
